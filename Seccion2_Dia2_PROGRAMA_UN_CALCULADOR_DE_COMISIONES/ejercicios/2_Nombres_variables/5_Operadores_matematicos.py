#  Operaciones matemáticas básicas
a = 10
b = 3
suma = a + b
resta = a - b
multiplicacion = a * b
division = a / b
modulo = a % b
print("Suma:", suma)
print("Resta:", resta)
print("Multiplicación:", multiplicacion)
print("División:", division)
print("Módulo:", modulo)

#  Operaciones con números flotantes
x = 5.5
y = 2.0
suma_flotante = x + y
print("Suma de flotantes:", suma_flotante)


#  Operaciones combinadas
resultado = (a + b) * (x - y) / b
print("Resultado de operaciones combinadas:", resultado)

#Operador de potencia
potencia = a ** b
print("Potencia:", potencia)

# Modulo con números flotantes (resto de la división)
modulo_flotante = x % y
print("Módulo de flotantes:", modulo_flotante)

# División entera o al piso
division_entera = a // b
print("División entera:", division_entera)