# Operadores de comparación
a = 5
b = 10
print(a > b)  # False
print(a < b)  # True
print(a == b) # False
print(a != b) # True

# Operadores lógicos
x = True
y = False
print(x and y)  # False
print(x or y)   # True
print(not x)    # False
print(not y)    # True

# Combinando operadores de comparación y lógicos
num = 7
print(num > 5 and num < 10)  # True
print(num < 5 or num > 10)    # False

